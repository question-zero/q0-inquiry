class Rules(unittest.TestCase):
    def test_spans_widen_to_word_boundaries_and_skip_outer_whitespace(self):
        text = "before " + GROK_SENTENCE + " after"
        windows = {bl.normalize(GROK_SENTENCE[i:i + bl.W])[0] for i in range(3, len(GROK_SENTENCE) - bl.W)}
        (a, b), = bl.window_spans(text, windows)
        self.assertTrue(text[a:b].startswith("mind that"), text[a:b])  # widened to the word, not the sentence
        self.assertEqual(text[b:], ". after")

    def test_curly_quotes_and_line_breaks_do_not_hide_a_quotation(self):
        windows = {bl.normalize(GROK_SENTENCE)[0][i:i + bl.W] for i in range(len(GROK_SENTENCE) - bl.W + 1)}
        wrapped = GROK_SENTENCE.replace(" shared ", "\n  shared ").replace("it knows", "it ’knows")
        self.assertEqual(len(bl.window_spans(wrapped, windows)), 1)

    def test_markers_are_valid_as_plain_yaml_values(self):
        for mark in (bl.ID_MARK, bl.LITERAL_MARK, bl.GROK_MARK, bl.FIELD_MARK):
            self.assertEqual(yaml.safe_load(f"a: {mark}\nb: x {mark} y\n"), {"a": mark, "b": f"x {mark} y"})

    def test_an_identifier_prefix_inside_another_token_is_left_alone(self):
        pat = bl.id_pattern([ID])
        self.assertEqual(pat.sub("X", f"{ID[:8]}zz {ID} {ID[:10]}"), f"{ID[:8]}zz X X")


