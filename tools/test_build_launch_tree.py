    def test_the_scan_reads_nested_and_escaped_forms(self):
        b = bl.Builder(self.cfg, bl.Tree(self.repo, "HEAD"))
        nested = json.dumps({"outer": json.dumps({"inner": "id " + ID})})
        escaped = "id " + "".join(f"\\u{ord(c):04x}" for c in ID)
        self.assertGreater(b.scan("sessions/a/x.json", nested.encode()), 0)
        self.assertGreater(b.scan("notes/x.md", ("---\na: 1\n---\n\n" + escaped + "\n").encode()), 0)
        self.assertGreater(b.scan("notes/x.md", ("---\n'" + ID + "': 1\n---\n\nbody\n").encode()), 0)
        self.assertGreater(b.scan(f"sessions/{ID}/x.txt", b"clean"), 0)  # the path itself
        self.assertEqual(b.scan("notes/x.md", b"---\na: 1\n---\n\nclean body\n"), 0)

    def test_round_two_readings_raw_text_paths_and_escaped_quotations(self):  # GPT-6 LX1, round 2
        b = bl.Builder(self.cfg, bl.Tree(self.repo, "HEAD"))
        escaped_id = "".join(f"\\u{ord(c):04x}" for c in ID)
        self.assertGreater(b.scan("sessions/a/x.json", ('{"a": 1} trailing ' + escaped_id).encode()), 0)
        self.assertGreater(b.scan("sessions/a/" + "".join(f"%{ord(c):02X}" for c in ID) + ".txt", b"clean"), 0)
        escaped_short = "".join(f"\\u{ord(c):04x}" for c in SHORT)
