class KnownQuotations(Base):  # GPT-6 RC2: known quotations at any length
    def test_short_grok_quotations_are_withheld_but_words_and_earlier_phrases_stay(self):
        self.build()
        other = self.read("rounds/01-deliberation/responses/other.md")
        self.assertNotIn("refusal “" + SHORT, other)  # the attributed quotation is withheld
        self.assertIn("“" + bl.GROK_MARK + "”", other)
        self.assertIn('"ledger"', other)  # one word: not a quotation of Grok's text
        self.assertIn('"unconventional reasoning"', other)  # its earliest source is the statement
        self.assertIn("> " + bl.GROK_MARK, other)  # a blockquote of Grok
        # two words with no attribution in their paragraph, and a model label, are not known quotations
        self.assertIn(f"Later the phrase \"{SHORT}\" came up again.", other)
        self.assertIn("The label \"Grok X\" was noted.", other)

    def test_the_four_attributed_forms_from_review_are_found(self):  # GPT-6 RC2, round 2
        grok = bl.GrokText(bl.Tree(self.repo, "HEAD"))
        cases = [f"Grok called it '{SHORT}' there.",
                 f"Grok called it `{SHORT}` there.",
                 f"The phrase \"{SHORT}\" comes from Grok's answer.",
                 f"As Grok put it:\n\n> {SHORT}\n\nThat ends the quotation."]
        for text in cases:
            with self.subTest(text=text[:30]):
                spans = grok.quote_spans(text)
                self.assertEqual([text[a:b] for a, b in spans], [SHORT])
        self.assertEqual(grok.quote_spans(f"Nobody named here said \"{SHORT}\" at all."), [])
        # a withholding marker nearby is not an attribution, so a second pass changes nothing
        self.assertEqual(grok.quote_spans(f"It said \"{bl.GROK_MARK}\" and later \"{SHORT}\" here."), [])
        self.assertEqual(grok.quote_spans(f"[WITHHELD: rights check D1, Grok output; see manifest] \"{SHORT}\""), [])
        self.assertEqual(grok.quote_spans("It isn't Grok's, and it's fine."), [])  # apostrophes don't pair up
        # the closing mark of one code span and the opening mark of the next are not a quotation
        self.assertEqual(grok.quote_spans(f"Grok: `a.sh` {SHORT} `b.log`"), [])

    def test_origin_follows_the_stage_order_ignoring_case(self):
        grok = bl.GrokText(bl.Tree(self.repo, "HEAD"))
        self.assertTrue(grok.origin_is_grok(SHORT))
        self.assertTrue(grok.origin_is_grok(SHORT.upper()))
        self.assertFalse(grok.origin_is_grok("Unconventional Reasoning"))
        self.assertFalse(grok.origin_is_grok("not in any source at all"))
        self.assertTrue(grok.quotes_grok(SHORT, "Grok called refusal "))
        self.assertFalse(grok.quotes_grok(SHORT, "Earlier text. " + "Grok. " + "\n\nA new paragraph: "))


